import os
import sys
import subprocess
import pandas as pd


# Get the main project directory
BASE_DIR = os.path.dirname(
    os.path.dirname(
        os.path.abspath(__file__)
    )
)


def generate_hybrid_schedule():
    """
    Runs the existing Hybrid AI scheduler
    and returns the generated schedule.
    """

    algorithm_file = os.path.join(
        BASE_DIR,
        "algorithms",
        "hybrid_scheduler.py"
    )

    # Run the existing Hybrid AI algorithm
    result = subprocess.run(
        [
            sys.executable,
            algorithm_file
        ],
        cwd=BASE_DIR,
        capture_output=True,
        text=True
    )

    # Check whether the algorithm ran successfully
    if result.returncode != 0:
        raise Exception(
            result.stderr
        )

    # Output file generated by the algorithm
    output_file = os.path.join(
        BASE_DIR,
        "outputs",
        "hybrid_final_schedule.csv"
    )

    # Check whether output exists
    if not os.path.exists(output_file):
        raise Exception(
            "Hybrid schedule file was not generated."
        )

    # Read generated schedule
    schedule_df = pd.read_csv(
        output_file
    )

    # Convert DataFrame to JSON-compatible format
    schedule = schedule_df.to_dict(
        orient="records"
    )

    return {
        "success": True,
        "schedule": schedule,
        "fitness_output": result.stdout
    }